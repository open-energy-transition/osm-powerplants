def get_region(name: str) -> list[str]:
    """Return the country list for a region, raising a helpful error if unknown.

    Parameters
    ----------
    name : str
        Region key (e.g. ``"europe"``, ``"southeastern_asia"``).

    Returns
    -------
    list[str]
        Country names resolvable by ``pycountry.countries.lookup``.
    """
    try:
        return REGIONS[name]
    except KeyError:
        available = ", ".join(sorted(REGIONS))
        raise KeyError(f"unknown region '{name}'. available: {available}") from None
