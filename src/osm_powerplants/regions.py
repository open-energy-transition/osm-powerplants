"""
Regional country groupings for global OSM power-plant extraction.

The global dataset is produced by extracting each region independently (in
parallel CI jobs) and merging the regional outputs. Splitting by region keeps
any single Overpass run from exceeding practical time limits and lets us
regenerate individual regions without re-fetching the world.

Groupings follow the UN M49 geoscheme with two pragmatic deviations:
    - Cyprus is placed in ``europe`` (as in EU membership) rather than
      Western Asia.
    - ``russia`` is carved out as a standalone region because Russia alone
      is heavier than several M49 regions combined.

All country names are resolvable via ``pycountry.countries.lookup`` and are
consumed by ``osm_powerplants.interface.validate_countries``. Kosovo is
intentionally absent: it cannot be queried via Overpass and is handled via
the ``omitted_countries`` key in config.yaml, not here.
"""

